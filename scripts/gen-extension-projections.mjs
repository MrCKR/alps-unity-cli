// Generates compile-time projections from extension-owned manifests and bridge specs.
// extension.json and extensions/<id>/bridge/domains/*.ts remain the only authored sources.

import { createRequire } from "node:module";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ts = require("typescript");
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const EXTENSIONS_DIR = join(ROOT, "extensions");
const REGISTRY_OUTPUT = join(ROOT, "src", "extensions", ".generated-registry-data.ts");
const BRIDGE_OUTPUT_DIR = join(ROOT, "src", "extensions", ".generated-bridge-domains");
const HEADER = "// <auto-generated by scripts/gen-extension-projections.mjs />\n// Generated from extension-owned sources. Do not edit.\n";

function fail(message) {
  throw new Error(`extension projection generation failed: ${message}`);
}

function label(id, subject) {
  return `extension ${JSON.stringify(id)} ${subject}`;
}

function assertString(value, subject) {
  if (typeof value !== "string" || value.length === 0) fail(`${subject} must be a non-empty string`);
}

function claim(owners, kind, name, id) {
  assertString(name, label(id, `${kind} name`));
  const previous = owners[kind].get(name);
  if (previous) fail(`duplicate ${kind} ownership for ${JSON.stringify(name)}: extensions ${JSON.stringify(previous)} and ${JSON.stringify(id)}`);
  owners[kind].set(name, id);
}

function validateInclude(id, extensionDir, include) {
  if (!Array.isArray(include) || include.length === 0) fail(`${label(id, "unityInstall.include")} must be a non-empty array`);
  const seen = new Set();
  for (const entry of include) {
    assertString(entry, label(id, "unityInstall.include entry"));
    const normalized = entry.replaceAll("\\", "/");
    if (normalized.startsWith("/") || normalized.split("/").includes("..")) fail(`${label(id, "unityInstall.include")} has unsafe path ${JSON.stringify(entry)}`);
    if (seen.has(normalized)) fail(`${label(id, "unityInstall.include")} duplicates ${JSON.stringify(entry)}`);
    seen.add(normalized);
    const target = resolve(extensionDir, normalized);
    const relativeTarget = relative(extensionDir, target);
    if (relativeTarget.startsWith(`..${sep}`) || relativeTarget === ".." || !existsSync(target)) fail(`${label(id, "unityInstall.include")} references missing path ${JSON.stringify(entry)}`);
    if (normalized.endsWith("/") && !statSync(target).isDirectory()) fail(`${label(id, "unityInstall.include")} expects directory ${JSON.stringify(entry)}`);
  }
  if (!seen.has("extension.json")) fail(`${label(id, "unityInstall.include")} must include "extension.json"`);
}

function validateManifest(manifest, directoryName, extensionDir, owners) {
  if (!manifest || typeof manifest !== "object" || Array.isArray(manifest)) fail(`extension ${JSON.stringify(directoryName)} manifest must be an object`);
  assertString(manifest.id, `extension ${JSON.stringify(directoryName)} manifest id`);
  if (manifest.id !== directoryName) fail(`extension ${JSON.stringify(directoryName)} manifest id is ${JSON.stringify(manifest.id)}; it must match the directory name`);
  if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(manifest.id)) fail(`${label(manifest.id, "manifest id")} must be kebab-case`);
  assertString(manifest.name, label(manifest.id, "name"));
  assertString(manifest.description, label(manifest.id, "description"));
  assertString(manifest.version, label(manifest.id, "version"));
  if (!Array.isArray(manifest.unityPackages)) fail(`${label(manifest.id, "unityPackages")} must be an array`);
  const packageIds = new Set();
  for (const dependency of manifest.unityPackages) {
    assertString(dependency?.packageId, label(manifest.id, "unityPackages packageId"));
    assertString(dependency?.displayName, label(manifest.id, `dependency ${JSON.stringify(dependency?.packageId)} displayName`));
    if (packageIds.has(dependency.packageId)) fail(`${label(manifest.id, "unityPackages")} duplicates dependency ${JSON.stringify(dependency.packageId)}`);
    packageIds.add(dependency.packageId);
  }
  if (!manifest.contributions || typeof manifest.contributions !== "object" || Array.isArray(manifest.contributions)) fail(`${label(manifest.id, "contributions")} must be an object`);
  for (const field of ["tools", "csharpEntries"]) {
    if (manifest.contributions[field] !== undefined && !Array.isArray(manifest.contributions[field])) fail(`${label(manifest.id, `contributions.${field}`)} must be an array`);
  }
  for (const tool of manifest.contributions.tools ?? []) {
    claim(owners, "tool", tool?.name, manifest.id);
    if (tool.requiresPackages !== undefined) {
      if (!Array.isArray(tool.requiresPackages)) fail(`${label(manifest.id, `tool ${JSON.stringify(tool.name)}`)} requiresPackages must be an array`);
      const required = new Set();
      for (const packageId of tool.requiresPackages) {
        assertString(packageId, label(manifest.id, `tool ${JSON.stringify(tool.name)} dependency`));
        if (required.has(packageId)) fail(`${label(manifest.id, `tool ${JSON.stringify(tool.name)}`)} duplicates dependency ${JSON.stringify(packageId)}`);
        required.add(packageId);
      }
    }
  }
  for (const entry of manifest.contributions.csharpEntries ?? []) {
    assertString(entry?.type, label(manifest.id, "csharp entry type"));
    if (entry.method !== undefined) assertString(entry.method, label(manifest.id, `csharp entry ${JSON.stringify(entry.type)} method`));
    claim(owners, "csharp entry", `${entry.type}${entry.method ? `.${entry.method}` : ""}`, manifest.id);
  }
  if (manifest.unityInstall?.layout !== "directory") fail(`${label(manifest.id, "unityInstall.layout")} must be "directory"`);
  validateInclude(manifest.id, extensionDir, manifest.unityInstall?.include);
}

function bridgeToolNames(sourcePath, id) {
  const source = ts.createSourceFile(sourcePath, readFileSync(sourcePath, "utf8"), ts.ScriptTarget.ES2022, true, ts.ScriptKind.TS);
  let specArray;
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement) || !statement.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)) continue;
    for (const declaration of statement.declarationList.declarations) {
      if (!ts.isIdentifier(declaration.name) || !declaration.name.text.endsWith("BridgeSpecs")) continue;
      const initializer = declaration.initializer;
      specArray = initializer && ts.isCallExpression(initializer) ? initializer.arguments[0] : initializer;
    }
  }
  if (!specArray || !ts.isArrayLiteralExpression(specArray)) fail(`${label(id, "bridge spec")} must export a *BridgeSpecs array`);
  const names = [];
  for (const element of specArray.elements) {
    if (!ts.isObjectLiteralExpression(element)) fail(`${label(id, "bridge spec")} contains a non-object spec entry`);
    const property = element.properties.find((candidate) => ts.isPropertyAssignment(candidate) && candidate.name.getText(source) === "toolName");
    if (!property || !ts.isPropertyAssignment(property) || !ts.isStringLiteral(property.initializer)) {
      const line = source.getLineAndCharacterOfPosition(element.getStart(source)).line + 1;
      fail(`${label(id, "bridge spec")} entry at line ${line} has no string toolName`);
    }
    names.push(property.initializer.text);
  }
  return names;
}

function validateBridgeSpec(manifest, sourcePath, bridgeOwners) {
  const specNames = bridgeToolNames(sourcePath, manifest.id);
  const specSet = new Set();
  for (const name of specNames) {
    if (specSet.has(name)) fail(`${label(manifest.id, "bridge spec")} duplicates toolName ${JSON.stringify(name)}`);
    specSet.add(name);
    const previous = bridgeOwners.get(name);
    if (previous) fail(`duplicate bridge spec ownership for ${JSON.stringify(name)}: extensions ${JSON.stringify(previous)} and ${JSON.stringify(manifest.id)}`);
    bridgeOwners.set(name, manifest.id);
  }
  const manifestNames = new Set((manifest.contributions.tools ?? []).map((tool) => tool.name));
  for (const name of [...manifestNames].sort()) if (!specSet.has(name)) fail(`${label(manifest.id, "manifest contribution")} ${JSON.stringify(name)} is missing from its bridge spec toolName entries`);
  for (const name of [...specSet].sort()) if (!manifestNames.has(name)) fail(`${label(manifest.id, "bridge spec toolName")} ${JSON.stringify(name)} is missing from manifest contributions.tools`);
}

function csharpTokens(source) {
  const tokens = [];
  for (let index = 0; index < source.length;) {
    const character = source[index];
    if (/\s/.test(character)) { index++; continue; }
    if (source.startsWith("//", index)) { index = source.indexOf("\n", index); if (index < 0) break; continue; }
    if (source.startsWith("/*", index)) { index = source.indexOf("*/", index + 2); if (index < 0) fail("unterminated C# block comment"); index += 2; continue; }
    if (character === '"') {
      let value = ""; index++;
      while (index < source.length && source[index] !== '"') {
        if (source[index] === "\\") index++;
        value += source[index++];
      }
      if (source[index] !== '"') fail("unterminated C# string");
      tokens.push({ kind: "string", value }); index++; continue;
    }
    if (/[A-Za-z_]/.test(character)) {
      let end = index + 1;
      while (end < source.length && /[A-Za-z0-9_]/.test(source[end])) end++;
      tokens.push({ kind: "identifier", value: source.slice(index, end) }); index = end; continue;
    }
    tokens.push({ kind: "punctuation", value: character }); index++;
  }
  return tokens;
}

function inspectCsharpCapabilities(extensionDir, id) {
  const capabilities = [];
  const files = [];
  const visit = (directory) => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) visit(path);
      else if (entry.isFile() && entry.name.endsWith(".cs")) files.push(path);
    }
  };
  visit(join(extensionDir, "unitypkg"));
  for (const sourcePath of files.sort()) {
    const tokens = csharpTokens(readFileSync(sourcePath, "utf8"));
    let namespaceName = "";
    for (let index = 0; index < tokens.length; index++) {
      if (tokens[index].value === "namespace") {
        const names = [];
        for (index++; tokens[index] && tokens[index].value !== "{"; index++) if (tokens[index].kind === "identifier") names.push(tokens[index].value);
        namespaceName = names.join(".");
        continue;
      }
      if (tokens[index].value !== "class") continue;
      const className = tokens[index + 1]?.value;
      let cursor = index + 2;
      while (tokens[cursor] && tokens[cursor].value !== "{" && tokens[cursor].value !== ";") cursor++;
      const header = tokens.slice(index + 2, cursor).map((token) => token.value);
      if (header.includes("IUnityCliContext")) fail(`${relativePath}: legacy IUnityCliContext authoring is forbidden; define an IUnityCliTool instead`);
      const kind = header.includes("IUnityCliTool") ? "tool" : undefined;
      if (!kind) continue;
      let name;
      for (let body = cursor; body < tokens.length - 2; body++) {
        if (tokens[body].value === "Name" && tokens[body + 1].value === "=" && tokens[body + 2].kind === "string") { name = tokens[body + 2].value; break; }
      }
      if (!namespaceName || !className || !name) fail(`${label(id, `C# capability ${relative(ROOT, sourcePath)}`)} must use the one-file convention with namespace, class, interface, and descriptor Name`);
      capabilities.push({ kind, name, type: `${namespaceName}.${className}`, path: relative(ROOT, sourcePath).replaceAll("\\", "/") });
    }
  }
  return capabilities;
}

function validateCsharpCapabilities(manifest, extensionDir) {
  const actual = inspectCsharpCapabilities(extensionDir, manifest.id);
  const actualTypes = new Map();
  const actualNames = { tool: new Map(), context: new Map() };
  for (const capability of actual) {
    if (actualTypes.has(capability.type)) fail(`${label(manifest.id, "C# implementation")} duplicates type ${JSON.stringify(capability.type)}`);
    if (actualNames[capability.kind].has(capability.name)) fail(`${label(manifest.id, "C# implementation")} duplicates ${capability.kind} Name ${JSON.stringify(capability.name)}`);
    actualTypes.set(capability.type, capability);
    actualNames[capability.kind].set(capability.name, capability);
  }
  const claims = new Set((manifest.contributions.csharpEntries ?? []).map((entry) => entry.type));
  if (claims.size !== (manifest.contributions.csharpEntries ?? []).length) fail(`${label(manifest.id, "manifest csharpEntries")} duplicates a type claim`);
  for (const type of [...claims].sort()) if (!actualTypes.has(type)) fail(`${label(manifest.id, "manifest csharpEntries claim")} ${JSON.stringify(type)} has no IUnityCliTool implementation`);
  for (const type of [...actualTypes.keys()].sort()) if (!claims.has(type)) fail(`${label(manifest.id, "C# implementation")} ${JSON.stringify(type)} is not claimed by contributions.csharpEntries`);
  for (const kind of ["tool", "context"]) {
    const claimed = new Set((manifest.contributions[`${kind}s`] ?? []).map((entry) => kind === "tool" ? entry.name : entry.key));
    for (const name of [...claimed].sort()) if (!actualNames[kind].has(name)) fail(`${label(manifest.id, `manifest ${kind} claim`)} ${JSON.stringify(name)} has no C# descriptor Name`);
    for (const name of [...actualNames[kind].keys()].sort()) if (!claimed.has(name)) fail(`${label(manifest.id, `C# ${kind} descriptor Name`)} ${JSON.stringify(name)} is not claimed by the manifest`);
  }
}

function projectBridgeSource(sourcePath) {
  const projected = readFileSync(sourcePath, "utf8")
    .replaceAll('from "../args.js"', 'from "../../bridge/args.js"')
    .replaceAll('from "../types.js"', 'from "../../bridge/types.js"');
  if (/from ["']\.\.\/(args|types)\.js["']/.test(projected)) fail(`unrewritten bridge import in ${relative(ROOT, sourcePath).replaceAll("\\", "/")}`);
  return `${HEADER}\n${projected}`;
}

function constantName(id) {
  return `${id.replaceAll("-", "_").toUpperCase()}_MANIFEST`;
}

function registrySource(manifests) {
  const declarations = manifests.map((manifest) => `export const ${constantName(manifest.id)}: ExtensionManifest = ${JSON.stringify(manifest, null, 2)};`).join("\n\n");
  const constants = manifests.map((manifest) => constantName(manifest.id)).join(",\n  ");
  return `${HEADER}\nimport type { ExtensionManifest } from "./types.js";\n\n${declarations}\n\nexport const BUILTIN_EXTENSION_MANIFESTS: ExtensionManifest[] = [\n  ${constants}\n];\n`;
}

function generate() {
  if (!existsSync(EXTENSIONS_DIR)) fail(`missing extensions directory: ${EXTENSIONS_DIR}`);
  const directories = readdirSync(EXTENSIONS_DIR, { withFileTypes: true }).filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();
  const owners = { tool: new Map(), context: new Map(), "csharp entry": new Map() };
  const bridgeOwners = new Map();
  const entries = [];
  for (const directoryName of directories) {
    const extensionDir = join(EXTENSIONS_DIR, directoryName);
    const manifestPath = join(extensionDir, "extension.json");
    if (!existsSync(manifestPath)) fail(`extension ${JSON.stringify(directoryName)} is missing extension.json`);
    let manifest;
    try {
      manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    } catch (error) {
      fail(`extension ${JSON.stringify(directoryName)} has invalid extension.json: ${error instanceof Error ? error.message : String(error)}`);
    }
    validateManifest(manifest, directoryName, extensionDir, owners);
    validateCsharpCapabilities(manifest, extensionDir);
    const domainDir = join(extensionDir, "bridge", "domains");
    if (!existsSync(domainDir)) fail(`${label(manifest.id, "bridge spec")} is missing directory bridge/domains`);
    const domainFiles = readdirSync(domainDir).filter((name) => name.endsWith(".ts")).sort();
    if (domainFiles.length !== 1) fail(`${label(manifest.id, "bridge spec")} must own exactly one bridge/domains/*.ts file; found ${domainFiles.length}`);
    const sourcePath = join(domainDir, domainFiles[0]);
    validateBridgeSpec(manifest, sourcePath, bridgeOwners);
    entries.push({ manifest, sourcePath, outputName: domainFiles[0] });
  }
  if (entries.length === 0) fail("no extension manifests found");
  mkdirSync(dirname(REGISTRY_OUTPUT), { recursive: true });
  rmSync(BRIDGE_OUTPUT_DIR, { recursive: true, force: true });
  mkdirSync(BRIDGE_OUTPUT_DIR, { recursive: true });
  writeFileSync(REGISTRY_OUTPUT, registrySource(entries.map((entry) => entry.manifest)), "utf8");
  for (const entry of entries) writeFileSync(join(BRIDGE_OUTPUT_DIR, entry.outputName), projectBridgeSource(entry.sourcePath), "utf8");
  console.log(`gen-extension-projections: generated ${entries.length} manifests and ${bridgeOwners.size} bridge specs`);
}

try {
  generate();
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
