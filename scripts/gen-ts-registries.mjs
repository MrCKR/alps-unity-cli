import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(process.argv[2] ?? resolve(dirname(fileURLToPath(import.meta.url)), ".."));

function sourceFiles(root) {
  const files = [];
  function visit(directory) {
    for (const entry of readdirSync(directory).sort()) {
      const path = join(directory, entry);
      if (statSync(path).isDirectory()) visit(path);
      else if (entry.endsWith(".ts") && !entry.startsWith(".generated-") && entry !== "define.ts") files.push(path);
    }
  }
  visit(root);
  return files;
}

function assertNoLegacyContextAuthoring() {
  const sourceRoot = join(ROOT, "src");
  if (existsSync(join(sourceRoot, "contexts"))) throw new Error("src/contexts: Context authoring directory is forbidden; define Tools under src/tools instead");
  for (const file of sourceFiles(sourceRoot)) {
    const text = readFileSync(file, "utf8");
    if (/\bdefineContext\s*(?:<|\()/.test(text)) throw new Error(`${relative(ROOT, file)}: legacy defineContext authoring is forbidden; define a Tool instead`);
  }
}

function generate(kind, directory, output) {
  if (!existsSync(directory)) throw new Error(`Registry source directory not found: ${directory}`);
  const call = "defineTool";
  const capabilities = [];
  for (const file of sourceFiles(directory)) {
    const text = readFileSync(file, "utf8");
    const defaultMatches = [...text.matchAll(new RegExp(`export\\s+default\\s+${call}(?:<[^;]+?>)?\\s*\\(`, "gs"))];
    const anyMatches = [...text.matchAll(new RegExp(`\\b${call}(?:<[^;]+?>)?\\s*\\(`, "gs"))];
    if (anyMatches.length === 0) continue;
    if (defaultMatches.length !== 1 || anyMatches.length !== 1) {
      throw new Error(`${relative(ROOT, file)} must contain exactly one default ${call}(...) capability`);
    }
    const tail = text.slice(defaultMatches[0].index);
    const name = /\bname\s*:\s*["']([^"']+)["']/.exec(tail)?.[1];
    if (!name) throw new Error(`${relative(ROOT, file)} must declare a literal capability name`);
    capabilities.push({ name, file });
  }

  const byName = new Map();
  for (const capability of capabilities) {
    const existing = byName.get(capability.name);
    if (existing) throw new Error(`Duplicate ${kind} capability ${capability.name}: ${relative(ROOT, existing)} and ${relative(ROOT, capability.file)}`);
    byName.set(capability.name, capability.file);
  }

  capabilities.sort((a, b) => a.name.localeCompare(b.name) || a.file.localeCompare(b.file));
  const outputDirectory = dirname(output);
  const imports = capabilities.map(({ file }) => {
    let path = relative(outputDirectory, file).replaceAll("\\", "/").replace(/\.ts$/, ".js");
    if (!path.startsWith(".")) path = `./${path}`;
    return `import ${JSON.stringify(path)};`;
  });
  const content = `// Generated by scripts/gen-ts-registries.mjs. Do not edit.\n${imports.join("\n")}\nimport \"./.generated-schemas.js\";\n`;
  writeFileSync(output, content, "utf8");
  process.stdout.write(`generated ${relative(ROOT, output)} (${capabilities.length} ${kind.toLowerCase()}s)\n`);
}

assertNoLegacyContextAuthoring();
generate("Tool", join(ROOT, "src", "tools"), join(ROOT, "src", "tools", ".generated-registry.ts"));
