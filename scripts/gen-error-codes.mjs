import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { classifyAll, FACT_TOKENS, FACT_SEMANTICS } from "./lib/error-code-taxonomy.mjs";
import { SYNONYM_TARGETS } from "./lib/error-code-renames.mjs";

const root = process.argv[2] ?? process.cwd();
const output = join(root, "contracts", "error-codes.json");
const { entries, dynamicSites, files } = classifyAll(root);

const codes = entries.map((entry) => {
  const tokens = entry.code.replace(/^E_/, "").split("_").filter(Boolean);
  return {
    code: entry.code,
    fact: entry.fact,
    effectStarted: entry.effectStarted ?? "unknown",
    transient: entry.transient ?? false,
    ...(entry.semanticsReason ? { semanticsOverrideReason: entry.semanticsReason } : {}),
    prefix: tokens[0] ?? null,
    renameTo: entry.status === "rename" && entry.fact ? entry.target : null,
    emitters: entry.files
  };
});

const synonyms = Object.keys(SYNONYM_TARGETS);
const report = {
  schemaVersion: 1,
  generatedBy: "scripts/gen-error-codes.mjs",
  factVocabulary: FACT_TOKENS.map(([fact]) => fact),
  semantics: FACT_SEMANTICS,
  synonyms,
  counts: {
    files: files.length,
    codes: codes.length,
    classified: codes.filter((entry) => entry.fact).length,
    unclassified: codes.filter((entry) => !entry.fact).length,
    dynamicConcatenationSites: dynamicSites.length
  },
  codes
};

writeFileSync(output, `${JSON.stringify(report, null, 2)}\n`, "utf8");

// 公开参考表：由登记表生成，保证 "每个码都有说明" 可被机器校验。
const rows = codes.map((entry) => `| \`${entry.code}\` | ${entry.fact ?? "unclassified"} | ${entry.effectStarted} | ${entry.transient ? "true" : "false"} | ${entry.emitters.slice(0, 2).join(", ")} |`);
const reference = [
  "# Error code reference (generated)",
  "",
  "Generated by `scripts/gen-error-codes.mjs`; do not edit by hand.",
  "`effectStarted` says whether the effect may already have happened when this code is returned; `transient` says whether the same request may be resubmitted after `retryAfterMs`.",
  "",
  "| Code | Fact | effectStarted | transient | Emitters |",
  "|---|---|---|---|---|",
  ...rows,
  ""
].join("\n");
writeFileSync(join(root, "docs", "error-codes-reference.md"), reference, "utf8");

console.log(JSON.stringify({ output: "contracts/error-codes.json", reference: "docs/error-codes-reference.md", ...report.counts }, null, 2));
