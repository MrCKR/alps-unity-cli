import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import test from "node:test";

interface Envelope {
  ok: boolean;
  requestId: string;
  data?: unknown;
  error?: { code: string; message: string; [key: string]: unknown };
}

const cliPath = fileURLToPath(new URL("../src/cli.js", import.meta.url));

/** 将一个 argv token 编码为 PowerShell 单引号字面量，保留 JSON 双引号和空格。 */
function quotePowerShell(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

/** 通过真实 pwsh 进程调用编译后的 CLI，并解析唯一 JSON envelope。 */
function runPowerShell(argv: string[], expectCompact = true): { status: number | null; lines: string[]; envelope: Envelope } {
  const script = `& ${quotePowerShell(process.execPath)} ${quotePowerShell(cliPath)} ${argv.map(quotePowerShell).join(" ")}`;
  const result = spawnSync("pwsh", ["-NoProfile", "-NonInteractive", "-Command", script], {
    cwd: process.cwd(),
    encoding: "utf8",
    env: { ...process.env, UNITY_CLI_ALLOW_NON_WINDOWS: "1" },
  });
  assert.equal(result.error, undefined, result.error?.message);
  const lines = result.stdout.trim().split(/\r?\n/);
  if (expectCompact) assert.equal(lines.length, 1, result.stderr || result.stdout);
  return { status: result.status, lines, envelope: JSON.parse(result.stdout) as Envelope };
}

function stable(envelope: Envelope): Omit<Envelope, "requestId"> {
  const { requestId: _requestId, ...result } = envelope;
  return result;
}

test("PowerShell global options are position independent", (context) => {
  if (!existsSync(cliPath)) return context.skip("compiled CLI is generated by build:test");
  const helpBefore = runPowerShell(["--pretty", "--help"], false);
  const helpAfter = runPowerShell(["--help", "--pretty"], false);
  assert.ok(helpBefore.lines.length > 1);
  assert.deepEqual(stable(helpBefore.envelope), stable(helpAfter.envelope));

  const instanceBefore = runPowerShell(["--instance", "missing-instance", "tools", "group"]);
  const instanceAfter = runPowerShell(["tools", "group", "--instance=missing-instance"]);
  assert.deepEqual(stable(instanceBefore.envelope), stable(instanceAfter.envelope));
});

test("PowerShell preserves parser error boundaries", (context) => {
  if (!existsSync(cliPath)) return context.skip("compiled CLI is generated by build:test");
  assert.equal(runPowerShell(["--instance", "tools", "group"]).envelope.error?.code, "E_OPTION_VALUE_REQUIRED");
  assert.equal(runPowerShell(["--unknown", "tools", "group"]).envelope.error?.code, "E_UNKNOWN_OPTION");
  assert.equal(runPowerShell(["--pretty=maybe", "tools", "group"]).envelope.error?.code, "E_OPTION_VALUE_INVALID");
  assert.equal(runPowerShell(["not-a-command", "--", "--instance"]).envelope.error?.code, "UNKNOWN_COMMAND");
});

test("PowerShell multi-token JSON reaches Tool input parsing as one value", (context) => {
  if (!existsSync(cliPath)) return context.skip("compiled CLI is generated by build:test");
  const result = runPowerShell([
    "tools",
    "run",
    "docs.get",
    "--input",
    "{\"api\":",
    "\"UnityEngine.Camera\"}",
    "--instance",
    "missing-instance",
  ]);
  assert.notEqual(result.envelope.error?.code, "E_TOOL_INPUT_JSON_INVALID");
});
